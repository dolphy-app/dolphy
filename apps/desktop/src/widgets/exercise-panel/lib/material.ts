/**
 * Материал урока по соглашению начинается с `# Название`. Название урока уже в
 * шапке экрана и на метке упражнения, поэтому в панели теории заголовок первого
 * уровня в начале не повторяют.
 */
export const stripLeadingTitle = (markdown: string): string =>
  markdown.replace(/^\s*#[ \t]+[^\n]*(\n+|$)/, '');
