/**
 * Применение изменений расширений на диске (установка, удаление, правка в
 * режиме разработчика): перечитать каталоги и привести к новому набору все
 * части, которые держат снимок, в том числе хост расширений.
 */
export interface ExtensionReloader {
  /**
   * Завершается, когда новый набор действует везде: снимок движка заменён,
   * хост расширений подтвердил замену. Отказ отдельного расширения — не отказ
   * перезагрузки (он виден в `extensions.list` как `invalid`). Бросает, только
   * если набор не удалось собрать: тогда прежний остаётся в силе.
   */
  reload(): Promise<void>;
}
